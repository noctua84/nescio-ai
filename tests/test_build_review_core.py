"""Tests for scripts/build_review_core.py and the generated review core.

`github-action/claude-review-core.yml` is GENERATED from
`claude-review-core.template.yml` plus `scripts/claude-review/*.sh`. These tests
pin: the committed core equals the generator's output (drift), `--check`
semantics, each build error, and the security property that makes build-time
inlining worth doing - no `run:` in the shipped core executes or sources a
file, because Claude has Write during the run and could rewrite one.
"""
import contextlib
import io
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import build_review_core as brc  # noqa: E402

GA = ROOT / "github-action"
CORE = GA / "claude-review-core.yml"
SCRIPTS = GA / "scripts" / "claude-review"

EXPECTED_SCRIPTS = {
    "resolve-pr-context.sh", "snapshot-state.sh", "publish-comments.sh",
    "open-learning-prs.sh", "merge-gate.sh",
}


def _lf(text):
    return text.replace("\r\n", "\n")


def _run_main(argv, ga):
    err = io.StringIO()
    out = io.StringIO()
    with contextlib.redirect_stderr(err), contextlib.redirect_stdout(out):
        code = brc.main(argv, ga=ga)
    return code, out.getvalue(), err.getvalue()


class _TmpGa(unittest.TestCase):
    """A throwaway github-action/ directory the generator can be pointed at."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.ga = Path(tmp.name) / "github-action"
        self.ga.mkdir()

    def write(self, rel, text):
        path = self.ga / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        return path

    def copy_real(self):
        shutil.copy(GA / brc.TEMPLATE_NAME, self.ga / brc.TEMPLATE_NAME)
        shutil.copytree(SCRIPTS, self.ga / "scripts" / "claude-review")
        shutil.copy(CORE, self.ga / brc.OUTPUT_NAME)

    def tiny(self, template=None, scripts=None):
        """A minimal template + scripts; returns nothing, files are written."""
        self.write(brc.TEMPLATE_NAME, template if template is not None else (
            "jobs:\n"
            "  j:\n"
            "    steps:\n"
            "      - name: s\n"
            "        run: |\n"
            "          # @inline scripts/claude-review/a.sh\n"))
        for name, text in (scripts if scripts is not None else
                           {"a.sh": "#!/usr/bin/env bash\necho hi\n"}).items():
            self.write(f"scripts/claude-review/{name}", text)


class DriftTest(unittest.TestCase):
    def test_committed_core_equals_generator_output(self):
        self.assertEqual(
            _lf(CORE.read_text(encoding="utf-8")), brc.build(GA),
            "claude-review-core.yml is stale: run `python scripts/build_review_core.py`")

    def test_committed_core_is_lf_only(self):
        self.assertNotIn(b"\r", CORE.read_bytes())

    def test_generated_header_is_the_first_line(self):
        first = CORE.read_text(encoding="utf-8").split("\n", 1)[0]
        self.assertTrue(first.startswith("# GENERATED by scripts/build_review_core.py"), first)
        self.assertIn("do not edit", first)

    def test_cli_check_passes_on_the_committed_core(self):
        proc = subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "build_review_core.py"), "--check"],
            capture_output=True, text=True, cwd=ROOT)
        self.assertEqual(proc.returncode, 0, proc.stderr)


class CheckModeTest(_TmpGa):
    def test_default_writes_core_with_lf_and_check_then_passes(self):
        self.copy_real()
        (self.ga / brc.OUTPUT_NAME).unlink()
        code, _, err = _run_main([], self.ga)
        self.assertEqual(code, 0, err)
        written = (self.ga / brc.OUTPUT_NAME).read_bytes()
        self.assertNotIn(b"\r", written)
        self.assertEqual(written.decode("utf-8"), brc.build(self.ga))
        self.assertEqual(_run_main(["--check"], self.ga)[0], 0)

    def test_check_fails_after_a_script_changes_and_writes_nothing(self):
        self.copy_real()
        self.assertEqual(_run_main(["--check"], self.ga)[0], 0)
        script = self.ga / "scripts" / "claude-review" / "merge-gate.sh"
        script.write_text(script.read_text(encoding="utf-8") + "echo changed\n",
                          encoding="utf-8", newline="\n")
        before = (self.ga / brc.OUTPUT_NAME).read_bytes()
        code, _, err = _run_main(["--check"], self.ga)
        self.assertEqual(code, 1)
        self.assertIn("stale", err)
        self.assertIn("echo changed", err)  # the diff hint shows the change
        self.assertEqual((self.ga / brc.OUTPUT_NAME).read_bytes(), before)

    def test_check_fails_when_the_core_is_missing(self):
        self.copy_real()
        (self.ga / brc.OUTPUT_NAME).unlink()
        self.assertEqual(_run_main(["--check"], self.ga)[0], 1)
        self.assertFalse((self.ga / brc.OUTPUT_NAME).exists())

    def test_check_fails_after_the_template_changes(self):
        self.copy_real()
        tpl = self.ga / brc.TEMPLATE_NAME
        tpl.write_text(tpl.read_text(encoding="utf-8").replace(
            "name: Claude Code Review (core)", "name: Something else"),
            encoding="utf-8", newline="\n")
        self.assertEqual(_run_main(["--check"], self.ga)[0], 1)


class InlineTest(_TmpGa):
    def test_indents_non_empty_lines_and_drops_the_shebang(self):
        self.tiny(scripts={"a.sh": "#!/usr/bin/env bash\n# c\nif x; then\n  y\n\nfi\n"})
        out = brc.build(self.ga)
        self.assertTrue(out.startswith(brc.HEADER))
        body = out.split("run: |\n", 1)[1]
        self.assertEqual(body, "          # c\n          if x; then\n            y\n\n          fi\n")
        self.assertNotIn("#!/usr", out)
        self.assertNotIn("# @inline", out)

    def test_no_trailing_whitespace_is_introduced(self):
        self.tiny(scripts={"a.sh": "#!/usr/bin/env bash\na\n\n\nb\n"})
        for line in brc.build(self.ga).split("\n"):
            self.assertEqual(line, line.rstrip(" "), repr(line))

    def test_crlf_script_is_normalised(self):
        self.tiny()
        (self.ga / "scripts" / "claude-review" / "a.sh").write_bytes(
            b"#!/usr/bin/env bash\r\necho hi\r\n")
        self.assertNotIn("\r", brc.build(self.ga))


class ErrorTest(_TmpGa):
    def assertBuildError(self, fragment):
        code, _, err = _run_main([], self.ga)
        self.assertEqual(code, 2, err)
        self.assertIn(fragment, err)
        self.assertFalse((self.ga / brc.OUTPUT_NAME).exists(), "must write nothing on error")
        code, _, err = _run_main(["--check"], self.ga)
        self.assertEqual(code, 2, err)

    def test_marker_naming_a_missing_script(self):
        self.tiny(scripts={})
        self.assertBuildError("missing script")

    def test_script_not_referenced_by_any_marker(self):
        self.tiny(scripts={"a.sh": "#!/usr/bin/env bash\ntrue\n",
                           "orphan.sh": "#!/usr/bin/env bash\ntrue\n"})
        self.assertBuildError("orphan.sh")

    def test_script_containing_an_expression(self):
        self.tiny(scripts={"a.sh": "#!/usr/bin/env bash\necho ${{ github.actor }}\n"})
        self.assertBuildError("${{")

    def test_marker_outside_a_run_block(self):
        for label, tpl in {
            "under env:": (
                "jobs:\n  j:\n    steps:\n      - name: s\n        env:\n"
                "          # @inline scripts/claude-review/a.sh\n"),
            "folded run: >": (
                "jobs:\n  j:\n    steps:\n      - name: s\n        run: >\n"
                "          # @inline scripts/claude-review/a.sh\n"),
            "top level": "# @inline scripts/claude-review/a.sh\njobs: {}\n",
            "a with: key": (
                "jobs:\n  j:\n    steps:\n      - name: s\n        with:\n"
                "          script: |\n"
                "            # @inline scripts/claude-review/a.sh\n"),
        }.items():
            with self.subTest(label):
                self.tiny(template=tpl)
                (self.ga / brc.OUTPUT_NAME).unlink(missing_ok=True)
                self.assertBuildError("not inside a `run: |` block")

    def test_marker_inside_a_run_block_after_blank_and_marker_lines_is_fine(self):
        self.tiny(
            template=("jobs:\n  j:\n    steps:\n      - name: s\n        run: |\n"
                      "          # @inline scripts/claude-review/a.sh\n\n"
                      "          # @inline scripts/claude-review/b.sh\n"),
            scripts={"a.sh": "#!/usr/bin/env bash\na\n", "b.sh": "#!/usr/bin/env bash\nb\n"})
        self.assertIn("          a\n          b\n", brc.build(self.ga).replace("\n\n", "\n"))

    def test_script_without_a_shebang(self):
        self.tiny(scripts={"a.sh": "echo hi\n"})
        self.assertBuildError("shebang")

    def test_marker_path_escaping_the_scripts_dir(self):
        self.tiny(template=("jobs:\n  j:\n    steps:\n      - name: s\n        run: |\n"
                            "          # @inline ../claude-review-core.yml\n"))
        self.assertBuildError("not a .sh file directly under")

    def test_missing_template(self):
        self.assertBuildError("cannot read")


class ShippedScriptsTest(unittest.TestCase):
    def test_the_five_step_scripts_exist_and_only_those(self):
        self.assertEqual({p.name for p in SCRIPTS.glob("*")}, EXPECTED_SCRIPTS)

    def test_every_script_has_the_shebang_and_no_expression(self):
        for script in sorted(SCRIPTS.glob("*.sh")):
            with self.subTest(script=script.name):
                data = script.read_bytes()
                self.assertTrue(data.startswith(b"#!/usr/bin/env bash\n"))
                self.assertNotIn(b"${{", data)
                self.assertNotIn(b"\r", data)

    def test_every_script_is_referenced_by_exactly_one_template_marker(self):
        template = (GA / brc.TEMPLATE_NAME).read_text(encoding="utf-8")
        for script in sorted(SCRIPTS.glob("*.sh")):
            with self.subTest(script=script.name):
                marker = f"# @inline scripts/claude-review/{script.name}"
                self.assertEqual(template.count(marker), 1)


# Command-position patterns that would run or load a file from a run: script.
_EXEC_PATTERNS = {
    "bash/sh <path>": re.compile(r"(?m)(?:^|[;&|(]|\bthen\b|\bdo\b)\s*(?:bash|sh|zsh|dash)\s+[^-\s]"),
    "source <file>": re.compile(r"(?m)(?:^|[;&|(]|\bthen\b|\bdo\b)\s*source\s+\S"),
    ". <file>": re.compile(r"(?m)(?:^|[;&|(]|\bthen\b|\bdo\b)\s*\.\s+\S"),
    "./<path> execution": re.compile(r"(?m)(?:^|[;&|(]|\bthen\b|\bdo\b)\s*\.{1,2}/\S"),
}
_PATH_PATTERNS = {
    ".github/ reference": re.compile(r"\.github/"),
    "scripts/claude-review reference": re.compile(r"scripts/claude-review"),
}


def exec_findings(run_text):
    found = [name for name, rx in {**_EXEC_PATTERNS, **_PATH_PATTERNS}.items()
             if rx.search(run_text)]
    return found


class NoFileExecutionTest(unittest.TestCase):
    """The shipped core must stay self-contained (security property)."""

    def test_detector_catches_what_it_claims_to(self):
        for bad in ("bash scripts/claude-review/x.sh", "source ./x.sh", ". ./x.sh",
                    "set -e\n./x.sh", "cd d && bash x.sh", "if a; then . x; fi",
                    "cat .github/workflows/a.yml", "cp scripts/claude-review/x /tmp"):
            with self.subTest(bad=bad):
                self.assertTrue(exec_findings(bad), bad)
        for good in ("echo hi", "bash -c 'x'", "# source of truth",
                     'echo "Source PR: $URL"', "gh api x | jq ."):
            with self.subTest(good=good):
                self.assertEqual(exec_findings(good), [], good)

    def test_no_run_in_the_generated_core_executes_or_sources_a_file(self):
        doc = yaml.safe_load(CORE.read_text(encoding="utf-8"))
        runs = [(jid, s.get("name"), str(s["run"]))
                for jid, job in doc["jobs"].items()
                for s in job.get("steps", []) if "run" in s]
        self.assertEqual(len(runs), 5, "expected the five inlined run: steps")
        for jid, name, run in runs:
            with self.subTest(job=jid, step=name):
                self.assertEqual(exec_findings(run), [])


