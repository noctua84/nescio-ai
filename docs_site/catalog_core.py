"""Shared primitives for every docs_site page generator.

Owns the pieces that are common to *any* catalog-style generator over this
repo's frontmatter: path constants (``SITE_DIR``, ``REPO_DIR``,
``DEFAULT_OUT_DIR``, ``REPO_BLOB_BASE``), the shared error type
(:class:`CatalogError`), the generated-file banner, the frontmatter parser
(``split_frontmatter`` and its scalar helpers), the ``Item``/``Catalog``
model, the per-file parser (``_parse_item``), the source-link helper
(``_source_link``), the item-heading regex (``ITEM_HEADING_RE``), and the
count-guard (``check_count``).

Why this is not in ``gen_catalog.py``
--------------------------------------
``gen_catalog.py`` was 732 lines against this repo's 400-line module
tripwire, and the new Commands/Theme/Lifecycle renderers (``gen_commands.py``,
``gen_theme.py``, ``gen_lifecycle.py``) all need these primitives while
``gen_catalog.build_pages`` needs to call back into *them* -- importing in
both directions would be a cycle. Pulling the shared primitives one module
lower breaks the cycle and shrinks ``gen_catalog.py`` (732 -> 672 lines); it
remains over the 400-line tripwire and carries a ``Module-check:`` verdict.

Stdlib only. This is *this module's own* constraint, not a claim about the
rest of ``docs_site/`` -- ``gen_theme.py`` now reads ``scripts/_crew_common``
directly through a top-level, repo-root ``sys.path`` insert (see that
module's docstring for why that is a deliberate, approved exception rather
than drift). ``catalog_core.py`` is the one module every other generator
imports, including `gen_theme.py` itself, so it is the one that must stay
importable with nothing from ``scripts/`` on ``PYTHONPATH`` regardless of
what its siblings do.

This module must never import ``gen_catalog`` (or any of its sibling
renderer modules). Doing so would recreate the exact cycle this extraction
exists to avoid.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

SITE_DIR = Path(__file__).resolve().parent
REPO_DIR = SITE_DIR.parent
DEFAULT_OUT_DIR = SITE_DIR / "docs"

# Used only to link each entry back at its source file. Kept as a constant so a
# rename of the canonical repo is one edit.
REPO_BLOB_BASE = "https://github.com/noctua84/nescio-ai/blob/main"


class CatalogError(RuntimeError):
    """The catalog could not be generated faithfully. Always fails the build."""


GENERATED_BANNER = (
    "<!-- Generated by docs_site/gen_catalog.py from the YAML frontmatter of\n"
    "     agents/*.md and skills/*/SKILL.md. Do not edit by hand. -->"
)


def generated_banner(source: str) -> str:
    """Generated-file banner naming ``source`` as this page's actual input.

    ``GENERATED_BANNER`` above is a literal, kept verbatim for ``skills.md``
    so that page's committed banner line does not churn for no reason. It is wrong
    for any other generated page, though -- ``agents.md`` now also names
    ``scripts/_crew_common.py`` as a source (the theme table), ``commands.md``
    is built from ``commands/*.md``, not from agent/skill frontmatter, and
    ``lifecycle.md`` is parsed out of ``agents/orchestrator.md``. Rather than
    hardcode a second (or third) literal that drifts the same way, this takes
    the source description as a parameter so ``gen_catalog.build_pages``
    can state the right one for each page it assembles.
    """
    return f"<!-- Generated by docs_site/gen_catalog.py from {source}. Do not edit by hand. -->"


# --------------------------------------------------------------------------
# Frontmatter parsing (house pattern: scripts/_wiki_common.py)
# --------------------------------------------------------------------------


def split_frontmatter(text: str) -> tuple[dict[str, object], str]:
    """Split a note into (frontmatter dict, body).

    Supports flat scalars and simple ``- `` lists, same as
    ``scripts/_wiki_common.py``. Returns ``({}, text)`` when no frontmatter
    block opens at the start or it never closes -- callers treat an empty dict
    as an error rather than skipping the file.
    """
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    block, body = text[4:end], text[end + 5:]
    fm: dict[str, object] = {}
    key: str | None = None
    for raw in block.splitlines():
        if not raw.strip():
            continue
        if raw.startswith("  - ") and key is not None:
            bucket = fm.setdefault(key, [])
            if isinstance(bucket, list):
                bucket.append(raw[4:].strip())
            continue
        if ":" in raw:
            k, _, v = raw.partition(":")
            key = k.strip()
            v = v.strip()
            fm[key] = v if v else []
    return fm, body


def _scalar(fm: dict[str, object], key: str) -> str:
    """Frontmatter value as a trimmed scalar string; '' when absent or a list."""
    value = fm.get(key)
    if isinstance(value, str):
        return _unquote(value.strip())
    return ""


def _unquote(value: str) -> str:
    """Strip one layer of matching surrounding quotes, if present."""
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


# --------------------------------------------------------------------------
# Model
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class Item:
    """One catalog entry, straight out of a file's frontmatter."""

    name: str
    description: str
    rel_path: str
    meta: dict[str, str] = field(default_factory=dict)


@dataclass
class Catalog:
    items: list[Item]
    warnings: list[str]


def _parse_item(path: Path, repo_dir: Path, expected_name: str) -> tuple[Item, list[str]]:
    """Parse one agent/skill file. Raises CatalogError on anything unusable."""
    rel_path = path.relative_to(repo_dir).as_posix()
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:  # pragma: no cover - filesystem failure
        raise CatalogError(f"{rel_path}: cannot be read ({exc})") from exc

    fm, _ = split_frontmatter(text)
    if not fm:
        raise CatalogError(
            f"{rel_path}: no closing '---' frontmatter fence at the top of the file"
        )

    name = _scalar(fm, "name")
    description = _scalar(fm, "description")
    missing = [k for k, v in (("name", name), ("description", description)) if not v]
    if missing:
        raise CatalogError(
            f"{rel_path}: frontmatter is missing required field(s): "
            + ", ".join(missing)
        )

    warnings: list[str] = []
    if name != expected_name:
        warnings.append(
            f"{rel_path}: frontmatter name '{name}' does not match its location "
            f"(expected '{expected_name}')"
        )

    meta = {k: v for k, v in fm.items() if isinstance(v, str) and k not in {"name", "description"}}
    meta = {k: _unquote(v.strip()) for k, v in meta.items()}
    return Item(name=name, description=description, rel_path=rel_path, meta=meta), warnings


# --------------------------------------------------------------------------
# Rendering helpers
# --------------------------------------------------------------------------

# One item section == one "### `name`" heading. Counting these in the *rendered
# text* is what makes the guard meaningful: it measures the page, not the list
# the page was built from.
ITEM_HEADING_RE = re.compile(r"^### `", re.MULTILINE)


def _source_link(rel_path: str) -> str:
    return f"[`{rel_path}`]({REPO_BLOB_BASE}/{rel_path})"


# --------------------------------------------------------------------------
# Count-guard
# --------------------------------------------------------------------------


def check_count(kind: str, page: str, live_paths: list[Path], repo_dir: Path) -> int:
    """Assert the rendered page carries one section per live definition file.

    Compares against the *live directory listing*, never a hardcoded number, so
    adding an agent or a skill can never red the build -- but a definition that
    exists on disk and failed to reach the page always does.
    """
    rendered = len(ITEM_HEADING_RE.findall(page))
    expected = len(live_paths)
    if rendered != expected:
        listing = ", ".join(p.relative_to(repo_dir).as_posix() for p in live_paths)
        raise CatalogError(
            f"count-guard: rendered {rendered} {kind} but the live directory "
            f"listing has {expected}. Something was dropped between the "
            f"filesystem and the page. Live listing: {listing}"
        )
    return rendered
