#!/usr/bin/env python3
"""NescioAI brand mark: a geometric little owl (noctua), plus derived assets.

Pure string generation — stdlib only, no Pillow, no Chromium and **no
fontTools**. Safe in CI.

Colours come from `brand.palette`; this module declares none of its own. That
retires the brand half of the palette drift the package exists to end (a second
near-black doing the job of `palette.text`, and an inline grey on the size
sheet doing the job of `palette.muted`).

The wordmark is outlined
-------------------------
"nescio" used to be live `<text>` in a mono face. Almost nothing on the open
web has that font installed — including the servers that render link previews —
so the social card was at risk of rendering the wordmark in whatever fallback
the renderer happened to reach for. Spec `docs/design/design-system.md` §3 calls
for outlining it, and `WORDMARK_PATH` below is that outline: real glyph
contours, in font units, immune to the font decision.

`WORDMARK_PATH` is **baked in as a constant** so that running this script needs
nothing but the stdlib. It is regenerated by an opt-in step that imports
fontTools lazily, inside a function, and is never reached on a normal run:

    python -m venv /tmp/ftvenv                       # local-only tooling,
    /tmp/ftvenv/bin/python -m pip install fonttools  # not a repo dependency
    /tmp/ftvenv/bin/python brand/make_brand.py --print-wordmark-path

That prints `upm`, the total advance and the `d` attribute; paste them into
`WORDMARK_UPM`, `WORDMARK_ADVANCE` and `WORDMARK_PATH`. Task T16 re-runs it
against IBM Plex Mono when that migration lands — the source font is the single
constant `WORDMARK_SOURCE`.

**Why Bold and not Regular.** Both call sites set the wordmark at `weight=700`,
so the live text they replaced rendered in Liberation Mono *Bold*; outlining
from Regular would silently thin the wordmark. Liberation Mono is monospaced
and carries no kerning, so the two weights are metrically identical (advance
7374/2048 em for the six glyphs) — only the stem weight differs. Both `.ttf`s
are committed under `brand/fonts/`.

Output directory, highest precedence first:
  1. ``--out DIR``
  2. ``$BRAND_OUT``
  3. ``<this file's directory>/dist`` — i.e. ``brand/dist/``, resolved relative
     to this file, not the current working directory.
"""
