def wordmark_width(size):
    """Rendered width of the wordmark at `size`, in user units.

    Identical to the advance width the live `<text>` element occupied, which is
    what makes `anchor="middle"` land in the same place as `text-anchor`.
    """
    return WORDMARK_ADVANCE * size / WORDMARK_UPM


def wordmark(x, y, size, fill, anchor="start"):
    """The wordmark as `<path>` outlines.

    `x`/`y` are the text origin — `y` is the baseline, and `anchor` mirrors
    SVG's `text-anchor`, so this is a drop-in replacement for the `<text>`
    element it supersedes.
    """
    s = size / WORDMARK_UPM
    width = wordmark_width(size)
    ox = {"start": x, "middle": x - width / 2, "end": x - width}[anchor]
    return (f'<path transform="translate({_n(ox)},{_n(y)}) '
            f'scale({_n(s)},{_n(-s)})" d="{WORDMARK_PATH}" fill="{fill}"/>')


def build_wordmark_outline(font_path=None, string=WORDMARK_TEXT):
    """Re-derive (upm, advance, path) from the source font. **Local-only.**

    Imports fontTools *inside the function* on purpose: `make_brand.py` must
    stay stdlib-only on a normal run so CI never grows a font dependency. This
    is reached only via `--print-wordmark-path`.
    """
    from fontTools.pens.svgPathPen import SVGPathPen  # noqa: PLC0415
    from fontTools.pens.transformPen import TransformPen  # noqa: PLC0415
    from fontTools.ttLib import TTFont  # noqa: PLC0415

    path = Path(font_path) if font_path else Path(__file__).resolve().parent / WORDMARK_SOURCE
    font = TTFont(path)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    # Legacy `kern` if present; this face has none, but a later source face
    # (T16's IBM Plex Mono) might, and the letterfit must respect it.
    kern_tables = font["kern"].kernTables if "kern" in font else []

    pieces, x, previous = [], 0, None
    for ch in string:
        name = cmap[ord(ch)]
        if previous is not None:
            for table in kern_tables:
                x += table.kernTable.get((previous, name), 0)
        pen = SVGPathPen(glyphs, ntos=lambda v: str(int(round(v))))
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, 1, x, 0)))
        drawn = pen.getCommands()
        if drawn:
            pieces.append(drawn)
        x += hmtx[name][0]
        previous = name
    return upm, x, "".join(pieces)


