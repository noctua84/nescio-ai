def _parser():
    ap = argparse.ArgumentParser(description="Generate the NescioAI brand SVGs.")
    ap.add_argument("--out", default=os.environ.get("BRAND_OUT"),
                    help="output directory (default: $BRAND_OUT, else brand/dist/)")
    ap.add_argument("--font", default=None,
                    help="source font for --print-wordmark-path "
                         f"(default: brand/{WORDMARK_SOURCE})")
    ap.add_argument("--print-wordmark-path", action="store_true",
                    help="re-derive the outlined wordmark from the source font "
                         "and print it; needs fontTools, writes nothing")
    return ap


def resolve_out_dir(argv=None):
    """--out, else $BRAND_OUT, else brand/dist/ next to this file."""
    return _out_dir(_parser().parse_args(argv))


def _out_dir(args):
    out = (Path(args.out).expanduser() if args.out
           else Path(__file__).resolve().parent / "dist")
    out.mkdir(parents=True, exist_ok=True)
    return out


def write(path, content):
    """Write UTF-8 with LF endings, so output is byte-identical on any OS."""
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)


if __name__ == "__main__":
    ARGS = _parser().parse_args()
    if ARGS.print_wordmark_path:
        UPM, ADVANCE, PATH_D = build_wordmark_outline(ARGS.font)
        print(f"WORDMARK_UPM = {UPM}")
        print(f"WORDMARK_ADVANCE = {ADVANCE}")
        print(f"WORDMARK_PATH = {PATH_D!r}")
    else:
        OUT_DIR = _out_dir(ARGS)
        for name, content in ASSETS:
            write(OUT_DIR / f"nescio-{name}.svg", content)
        print(f"brand svgs written -> {OUT_DIR}")
