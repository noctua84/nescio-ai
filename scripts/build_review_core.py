#!/usr/bin/env python3
"""Build github-action/claude-review-core.yml from its template and scripts.

The review core's shell steps live as real script files under
``github-action/scripts/claude-review/`` (tested directly, shellcheck-able).
The shipped workflow must stay ONE self-contained file: the installer copies it
alone, an org fork consumes it cross-repo, and Claude has Write during the run,
so a step must never execute a file Claude could have rewritten. So this
generator inlines each script into the workflow at build time.

    github-action/claude-review-core.template.yml   wiring; a `run: |` block
        holds one marker line instead of a script body:
            # @inline scripts/claude-review/<name>.sh   (path relative to github-action/)
    github-action/scripts/claude-review/*.sh         the script bodies
    github-action/claude-review-core.yml            GENERATED output - never edit

For each marker the script's content minus its shebang line is substituted,
every non-empty line prefixed with the marker's indentation (empty lines stay
empty, so no trailing whitespace is introduced).

Usage (from the repo root):

    python scripts/build_review_core.py           write the generated core (LF)
    python scripts/build_review_core.py --check   write nothing; exit 1 when the
                                                  committed core is stale

Exit status: 0 on success / up to date, 1 from --check when stale, 2 on a
build error (missing script, unreferenced script, `${{` in a script, a marker
outside a `run: |` block, ...).
"""
from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parent.parent
GA = REPO_DIR / "github-action"

TEMPLATE_NAME = "claude-review-core.template.yml"
OUTPUT_NAME = "claude-review-core.yml"
SCRIPTS_REL = "scripts/claude-review"

HEADER = (
    "# GENERATED by scripts/build_review_core.py from claude-review-core.template.yml "
    "and scripts/claude-review/*.sh — do not edit; edit those and re-run the generator.\n"
)

MARKER_RE = re.compile(r"^(?P<indent> *)# @inline (?P<path>\S+)[ \t]*$")
RUN_LINE = "run: |"


class BuildError(Exception):
    """A template/script problem the author must fix (exit status 2)."""


def _lf(text: str) -> str:
    return text.replace("\r\n", "\n")


def _read(path: Path) -> str:
    try:
        return _lf(path.read_bytes().decode("utf-8"))
    except OSError as exc:
        raise BuildError(f"cannot read {path}: {exc}") from exc
    except UnicodeDecodeError as exc:
        raise BuildError(f"{path} is not valid UTF-8: {exc}") from exc


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _check_in_run_block(lines: list[str], idx: int, indent: int, where: str) -> None:
    """The nearest shallower non-blank, non-marker line above must be `run: |`."""
    for j in range(idx - 1, -1, -1):
        line = lines[j]
        if not line.strip() or MARKER_RE.match(line):
            continue
        if _indent(line) >= indent:
            continue
        if line.strip() == RUN_LINE:
            return
        raise BuildError(
            f"{where}: marker is not inside a `{RUN_LINE}` block "
            f"(nearest enclosing line is {line.strip()!r})")
    raise BuildError(f"{where}: marker is not inside a `{RUN_LINE}` block")


def _load_script(ga: Path, scripts_dir: Path, rel: str, where: str) -> list[str]:
    path = (ga / rel).resolve()
    if path.parent != scripts_dir.resolve() or path.suffix != ".sh":
        raise BuildError(f"{where}: {rel!r} is not a .sh file directly under {SCRIPTS_REL}/")
    if not path.is_file():
        raise BuildError(f"{where}: marker names a missing script {rel!r}")
    text = _read(path)
    if "${{" in text:
        raise BuildError(
            f"{rel}: contains '${{{{' - values must reach a script through env:, "
            "never through expression interpolation")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    if not lines or not lines[0].startswith("#!"):
        raise BuildError(f"{rel}: line 1 must be a shebang (#!/usr/bin/env bash)")
    return lines[1:]


def build(ga: Path = GA) -> str:
    """Return the generated core's text; raise BuildError on any problem."""
    template = ga / TEMPLATE_NAME
    scripts_dir = ga / SCRIPTS_REL
    lines = _read(template).split("\n")
    out: list[str] = []
    referenced: set[Path] = set()
    for idx, line in enumerate(lines):
        m = MARKER_RE.match(line)
        if m is None:
            out.append(line)
            continue
        indent = len(m["indent"])
        where = f"{TEMPLATE_NAME}:{idx + 1}"
        _check_in_run_block(lines, idx, indent, where)
        body = _load_script(ga, scripts_dir, m["path"], where)
        referenced.add((ga / m["path"]).resolve())
        out.extend(m["indent"] + b if b else "" for b in body)
    if scripts_dir.is_dir():
        for script in sorted(scripts_dir.glob("*.sh")):
            if script.resolve() not in referenced:
                raise BuildError(
                    f"{SCRIPTS_REL}/{script.name} is not referenced by any "
                    f"`# @inline` marker in {TEMPLATE_NAME}")
    return HEADER + "\n" + "\n".join(out)


def _write_lf(path: Path, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def main(argv: list[str] | None = None, ga: Path = GA) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if the committed core differs")
    args = ap.parse_args(argv)
    try:
        expected = build(ga)
    except BuildError as exc:
        print(f"build_review_core: error: {exc}", file=sys.stderr)
        return 2
    target = ga / OUTPUT_NAME
    if args.check:
        try:
            current = _lf(target.read_bytes().decode("utf-8"))
        except (OSError, UnicodeDecodeError):
            current = None
        if current == expected:
            return 0
        print(f"build_review_core: {OUTPUT_NAME} is stale; "
              "run `python scripts/build_review_core.py` and commit the result.",
              file=sys.stderr)
        if current is not None:
            diff = list(difflib.unified_diff(
                current.split("\n"), expected.split("\n"),
                "committed", "generated", n=0, lineterm=""))
            for d in diff[:20]:
                print(d.encode("ascii", "replace").decode("ascii"), file=sys.stderr)
            if len(diff) > 20:
                print(f"... ({len(diff) - 20} more diff lines)", file=sys.stderr)
        return 1
    _write_lf(target, expected)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
